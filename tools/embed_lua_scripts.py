#!/usr/bin/env python3
"""Pack install/data/*.lua, then embed the ZIP as a portable C byte array."""
import argparse
from pathlib import Path
import zipfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--pack', type=Path, help='directory containing the Lua scripts')
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
archive = root / 'res/lua_script.zip'
if args.pack:
    scripts = sorted(args.pack.glob('*.lua'), key=lambda p: (p.name == 'vector.lua', p.name))
    if not any(p.name == 'vector.lua' for p in scripts):
        parser.error('vector.lua is required')
    with zipfile.ZipFile(archive, 'w', compression=zipfile.ZIP_DEFLATED) as bundle:
        for script in scripts:
            entry = zipfile.ZipInfo(script.name, date_time=(1980, 1, 1, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_DEFLATED
            entry.external_attr = 0o100644 << 16
            bundle.writestr(entry, script.read_bytes())
blob = archive.read_bytes()
header = root / 'res/lua_script_zip.h'
text = '/* Generated by tools/embed_lua_scripts.py from res/lua_script.zip. */\n'
text += 'static const unsigned char g_luaScriptZip[] = {\n'
text += ''.join('    ' + ', '.join(f'0x{b:02x}' for b in blob[i:i+16]) + ',\n'
                for i in range(0, len(blob), 16))
text += '};\n'
if not header.exists() or header.read_text() != text:
    header.write_text(text)
