#!/bin/sh
# Portable Makefile counterpart of cmake/EmbedShader.cmake.
set -eu
[ "$#" = 3 ] || { echo "usage: $0 input output C_variable" >&2; exit 2; }
case "$3" in ""|[0-9]*|*[!a-zA-Z0-9_]*) echo "Invalid C variable" >&2; exit 2 ;; esac
mkdir -p "$(dirname "$2")"
tmp="$2.tmp"
trap 'rm -f "$tmp"' EXIT HUP INT TERM
awk -v name="$3" '
BEGIN { print "/* Generated by tools/embed_shader.sh. */"; print "static const char " name "[] =" }
{
    printf "    \""
    for (i = 1; i <= length($0); ++i) {
        c = substr($0, i, 1)
        if (c == "\r") continue
        if (c == "\\" || c == "\"") printf "\\"
        printf "%s", c
    }
    print "\\n\""
}
END { print "    \"\";" }
' "$1" > "$tmp"
if cmp -s "$tmp" "$2"; then rm -f "$tmp"; else mv -f "$tmp" "$2"; fi
