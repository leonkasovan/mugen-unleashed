#!/bin/sh
# Embed a directory of text resources as C data, for the GNU Make build.
#
#   tools/embed_resources.sh <input-dir> <output.h> <prefix> <string|hex> <ext> [last]
#
# "string" writes one C string literal per file (res/configs); "hex" writes
# byte arrays plus an EmbeddedFile table (res/lua). <last> names a file to emit
# after the others; res/lua uses vector.lua so a partial restoration retries.
# The CMake ports use port/cmake/EmbedResourcesFile.cmake, which produces the
# same arrays and table.
set -eu
[ "$#" -ge 5 ] || { echo "usage: $0 <input-dir> <output.h> <prefix> <string|hex> <ext> [last]" >&2; exit 2; }
input=$1
output=$2
prefix=$3
mode=$4
ext=$5
last=${6-}
[ -d "$input" ] || { echo "no such directory: $input" >&2; exit 1; }
case $mode in string|hex) ;; *) echo "mode must be string or hex" >&2; exit 2 ;; esac
mkdir -p "$(dirname "$output")"
tmp="$output.tmp"
trap 'rm -f "$tmp"' EXIT HUP INT TERM
found=0
table=

emit()
{
    file=$1
    name=${file##*/}
    variable=g_${prefix}_$(printf '%s' "$name" | tr '.-' '__')
    [ -s "$file" ] || { echo "empty resource: $file" >&2; exit 1; }
    found=1
    case $mode in
    string)
        echo "static const char $variable[] ="
        awk '
            {
                printf "    \""
                for (i = 1; i <= length($0); ++i) {
                    c = substr($0, i, 1)
                    if (c == "\r") continue
                    if (c == "\\" || c == "\"") printf "\\"
                    printf "%s", c
                }
                print "\\n\""
            }
            END { print "    \"\";" }
        ' "$file"
        ;;
    hex)
        echo "static const unsigned char $variable[] = {"
        # CR is dropped at byte level, matching port/cmake/EmbedResourcesFile.cmake:
        # od prints one 0d for a real CR and pass 1 removes exactly those. Both
        # generators must embed the same bytes, so neither may do this by string
        # substitution on the values.
        od -An -v -tx1 "$file" | awk '
            {
                for (i = 1; i <= NF; ++i) {
                    if ($i == "0d") continue
                    if (n % 16 == 0) printf "    "
                    printf "0x%s,", $i
                    ++n
                    if (n % 16 == 0) printf "\n"
                    else printf " "
                }
            }
            END { if (n % 16 != 0) printf "\n" }
        '
        echo "};"
        echo
        table="${table}    { \"${name}\", ${variable}, sizeof(${variable}) },\n"
        ;;
    esac
}

{
    echo "/* Generated by tools/embed_resources.sh from ${input}/. Do not edit. */"
    for file in "$input"/*."$ext"; do
        [ -f "$file" ] || continue
        name=${file##*/}
        [ -n "$last" ] && [ "$name" = "$last" ] && continue
        emit "$file"
    done
    if [ -n "$last" ] && [ -f "$input/$last" ]; then
        emit "$input/$last"
    fi
    [ "$found" = 1 ] || { echo "no .$ext files in $input" >&2; exit 1; }
    if [ "$mode" = hex ]; then
        echo "#ifndef MUGEN_EMBEDDED_FILE_DEFINED"
        echo "#define MUGEN_EMBEDDED_FILE_DEFINED"
        echo "typedef struct EmbeddedFile {"
        echo "    const char *name;"
        echo "    const unsigned char *data;"
        echo "    unsigned int size;"
        echo "} EmbeddedFile;"
        echo "#endif"
        echo
        echo "static const EmbeddedFile g_${prefix}_files[] = {"
        printf '%b' "$table"
        echo "};"
    fi
} > "$tmp"
if cmp -s "$tmp" "$output"; then rm -f "$tmp"; else mv -f "$tmp" "$output"; fi
