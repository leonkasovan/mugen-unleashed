#!/bin/sh
# Embed res/configs/*.cfg as C string literals, for the GNU Make build.
#
#   tools/embed_configs.sh <config-dir> <output.h>
#
# The generated header defines g_config_<flattened-name> for every .cfg in the
# directory ('/' and '.' become '_'): mugen.win32.cfg -> g_config_mugen_win32_cfg.
# src/configembed.c includes it and writes the missing files into data/ at
# start-up. Line endings are normalised to LF so this and the CMake port
# (port/cmake/EmbedConfigsFile.cmake, which reads the files the same way) embed
# identical bytes on every host.
set -eu
[ "$#" = 2 ] || { echo "usage: $0 <config-dir> <output.h>" >&2; exit 2; }
[ -d "$1" ] || { echo "no such directory: $1" >&2; exit 1; }
mkdir -p "$(dirname "$2")"
tmp="$2.tmp"
trap 'rm -f "$tmp"' EXIT HUP INT TERM
{
    echo '/* Generated by tools/embed_configs.sh from res/configs/. Do not edit. */'
    found=0
    for file in "$1"/*.cfg; do
        [ -f "$file" ] || continue
        found=1
        name=${file##*/}
        variable=g_config_$(printf '%s' "$name" | tr '.-' '__')
        echo "static const char $variable[] ="
        awk '
            {
                printf "    \""
                for (i = 1; i <= length($0); ++i) {
                    c = substr($0, i, 1)
                    if (c == "\r") continue
                    if (c == "\\" || c == "\"") printf "\\"
                    printf "%s", c
                }
                print "\\n\""
            }
            END { print "    \"\";" }
        ' "$file"
    done
    [ "$found" = 1 ] || { echo "no .cfg files in $1" >&2; exit 1; }
} > "$tmp"
if cmp -s "$tmp" "$2"; then rm -f "$tmp"; else mv -f "$tmp" "$2"; fi
